#!/usr/bin/env node

import { execFile as execFileCallback } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { writeChunkedRegistry } from "./chunked-registry-writer.mjs";

const execFile = promisify(execFileCallback);

const CONFIGS = [
  {
    file: "slime-assets.generated.ts",
    banner: "// Generated by scripts/import-slime-assets.mjs. Do not edit by hand.",
    registries: [
      ["SLIME_WEB_ASSET_REGISTRY", "assets"],
      ["SLIME_WEB_CROWN_OVERLAY_REGISTRY", "crowns"],
      ["SLIME_WEB_HAPPY_HEART_OVERLAY_REGISTRY", "happy-hearts"],
    ],
    constants: ["SLIME_WEB_SHARED_ASSETS"],
  },
  {
    file: "slime-wearables.generated.ts",
    banner: "// Generated by scripts/import-slime-wearables.mjs. Do not edit by hand.",
    registries: [["SLIME_WEB_WEARABLE_REGISTRY", "wearables"]],
    constants: ["SLIME_WEARABLE_LAYER_ORDER"],
  },
  {
    file: "slime-ball-assets.generated.ts",
    banner: "// Generated registry chunks for slime-ball-assets.generated.ts. Do not edit by hand.",
    registries: [["SLIME_BALL_WEB_ASSET_REGISTRY", "ball-assets"]],
    aliases: [["SLIME_BALL_ASSET_REGISTRY", "SLIME_BALL_WEB_ASSET_REGISTRY"]],
  },
  {
    file: "slime-wearable-actions.generated.ts",
    banner: "// Generated by scripts/import-slime-wearable-actions.mjs. Do not edit.",
    registries: [["SLIME_WEB_WEARABLE_ACTION_REGISTRY", "wearable-actions"]],
  },
];

async function loadGeneratedModule(filePath) {
  const temporaryPath = `${filePath}.chunk-input.ts`;
  const moduleName = `./${path.basename(filePath, ".ts")}`;
  await fs.writeFile(
    temporaryPath,
    `import * as generated from ${JSON.stringify(moduleName)};\nprocess.stdout.write(JSON.stringify(generated));\n`,
    "utf8",
  );
  try {
    const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
    const tsxCli = path.join(projectRoot, "node_modules", "tsx", "dist", "cli.mjs");
    const { stdout } = await execFile(process.execPath, [tsxCli, temporaryPath], {
      cwd: path.dirname(filePath),
      maxBuffer: 128 * 1024 * 1024,
    });
    return JSON.parse(stdout);
  } finally {
    await fs.rm(temporaryPath, { force: true });
  }
}

export async function chunkGeneratedPetRegistries(directory = path.dirname(fileURLToPath(import.meta.url))) {
  const normalizedDirectory = path.resolve(directory);
  for (const config of CONFIGS) {
    const outputPath = path.join(normalizedDirectory, config.file);
    const source = await loadGeneratedModule(outputPath);
    await writeChunkedRegistry({
      outputPath,
      approvedRoots: [normalizedDirectory],
      allowedBaseNames: [config.file],
      banner: config.banner,
      registries: config.registries.map(([name, filePrefix]) => ({
        name,
        filePrefix,
        entries: Object.entries(source[name]),
      })),
      constants: (config.constants ?? []).map((name) => ({ name, value: source[name] })),
      aliases: (config.aliases ?? []).map(([name, target]) => ({ name, target })),
    });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/(.:)/, "$1"))) {
  chunkGeneratedPetRegistries().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}

function literal(value, continuationIndent = 0) {
  const padding = " ".repeat(continuationIndent);
  return JSON.stringify(value, null, 2).replace(/\n/g, `\n${padding}`);
}

function renderAssetEntry(entry) {
  return [
    `  ${JSON.stringify(entry.key)}: {`,
    `    key: ${JSON.stringify(entry.key)},`,
    `    evolution: ${JSON.stringify(entry.evolution)},`,
    `    color: ${JSON.stringify(entry.color)},`,
    `    action: ${JSON.stringify(entry.action)},`,
    "    imageScale: 4,",
    `    metadata: ${literal(entry.metadata, 4)},`,
    `    sheet: require(${JSON.stringify(`../assets/slimes/${entry.key}/sheet.png`)}),`,
    "  },",
  ].join("\n");
}

function renderCrownOverlay(overlay) {
  return [
    `  ${JSON.stringify(overlay.key)}: {`,
    `    key: ${JSON.stringify(overlay.key)},`,
    "    imageScale: 4,",
    `    differingPixels: ${overlay.differingPixels},`,
    `    overlay: require(${JSON.stringify(`../assets/slimes/overlays/${overlay.key}/overlay.png`)}),`,
    "  },",
  ].join("\n");
}

function renderHappyHeartOverlay(overlay) {
  return [
    `  ${JSON.stringify(overlay.key)}: {`,
    `    key: ${JSON.stringify(overlay.key)},`,
    `    evolution: ${JSON.stringify(overlay.evolution)},`,
    `    color: ${JSON.stringify(overlay.color)},`,
    '    action: "happy",',
    "    imageScale: 4,",
    `    metadata: ${literal(overlay.metadata, 4)},`,
    `    sheet: require(${JSON.stringify(`../assets/slimes/overlays/happy-heart/${overlay.key}/sheet.png`)}),`,
    "  },",
  ].join("\n");
}

function renderSharedAsset(value, requirePath) {
  return `{ ...${literal(value, 2)}, image: require(${JSON.stringify(requirePath)}) }`;
}

export function renderMobileSlimeRegistry(
  entries,
  overlays,
  happyHeartOverlays,
  shared,
  manifest,
) {
  const grassFloor = {
    key: "grass-floor",
    imageScale: 4,
    surfaceY: 44,
    slimeFootY: 56,
    source: "../assets/slimes/shared/grass-floor.png",
  };
  const cookie = {
    key: "cookie-shop-icon-256",
    imageScale: 1,
    source: "../assets/slimes/shared/cookie-shop-icon-256.png",
  };
  const sharedPuddle = shared.sharedPuddle
    ? {
        ...shared.sharedPuddle,
        imageScale: 4,
        source: "../assets/slimes/shared/water-puddle/sheet.png",
      }
    : null;

  return [
    "// Generated by scripts/import-slime-assets.mjs. Do not edit by hand.",
    "",
    "export const SLIME_MOBILE_ASSET_REGISTRY = {",
    entries.map(renderAssetEntry).join("\n"),
    "} as const;",
    "",
    "export const SLIME_MOBILE_CROWN_OVERLAY_REGISTRY = {",
    overlays.map(renderCrownOverlay).join("\n"),
    "} as const;",
    "",
    "export const SLIME_MOBILE_HAPPY_HEART_OVERLAY_REGISTRY = {",
    happyHeartOverlays.map(renderHappyHeartOverlay).join("\n"),
    "} as const;",
    "",
    "export const SLIME_MOBILE_SHARED_ASSETS = {",
    `  grassFloor: ${renderSharedAsset(grassFloor, grassFloor.source)},`,
    `  cookie: ${renderSharedAsset(cookie, cookie.source)},`,
    `  sharedPuddle: ${
      sharedPuddle
        ? renderSharedAsset(
            sharedPuddle,
            sharedPuddle.source,
          )
        : "null"
    },`,
    "} as const;",
    "",
    "export const SLIME_MOBILE_ANIMATION_MANIFEST = {",
    "  schemaVersion: 1,",
    "  imageScale: 4,",
    `  colors: ${literal(manifest.colors, 2)},`,
    `  evolutions: ${literal(manifest.evolutions, 2)},`,
    `  actions: ${literal(manifest.actions, 2)},`,
    `  playbackByAction: ${literal(manifest.playbackByAction, 2)},`,
    "  assets: SLIME_MOBILE_ASSET_REGISTRY,",
    "  crownOverlays: SLIME_MOBILE_CROWN_OVERLAY_REGISTRY,",
    "  happyHeartOverlays: SLIME_MOBILE_HAPPY_HEART_OVERLAY_REGISTRY,",
    "  shared: SLIME_MOBILE_SHARED_ASSETS,",
    "} as const;",
    "",
  ].join("\n");
}

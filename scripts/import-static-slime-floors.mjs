import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const sourceRoot = path.resolve(process.argv[2] ?? "");
const catalogPath = path.join(sourceRoot, "static-floor-tiers.json");
const webAssetRoot = path.join(repoRoot, "public", "creatures", "slimes", "official", "shared", "floors");
const mobileAssetRoot = path.join(repoRoot, "apps", "mobile", "assets", "slimes", "shared", "floors");
const webRegistryPath = path.join(repoRoot, "src", "lib", "pets", "static-floors.generated.ts");
const mobileRegistryPath = path.join(repoRoot, "apps", "mobile", "lib", "static-floors.generated.ts");

const expectedTiers = new Map([
  ["crystal-cave-floor", 1],
  ["moonlit-marble-floor", 1],
  ["royal-garden-floor", 1],
  ["celestial-gold-floor", 1],
  ["snow-ground-floor", 2],
  ["ancient-brick-floor", 2],
  ["cherry-stone-floor", 2],
  ["sand-trail-floor", 3],
  ["forest-soil-floor", 3],
  ["stone-floor", 3],
]);

function fail(message) {
  throw new Error(message);
}

async function sha256(filePath) {
  return crypto.createHash("sha256").update(await fs.readFile(filePath)).digest("hex");
}

async function readPixels(filePath, width, height) {
  const { data, info } = await sharp(filePath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  if (info.width !== width || info.height !== height || info.channels !== 4) {
    fail(`Unexpected PNG geometry: ${filePath}`);
  }
  return data;
}

function verifyBinaryAlpha(data, id) {
  for (let index = 3; index < data.length; index += 4) {
    if (data[index] !== 0 && data[index] !== 255) fail(`Non-binary alpha: ${id}`);
  }
}

function verifyNearestNeighbor(source, enlarged, id) {
  for (let y = 0; y < 64; y += 1) {
    for (let x = 0; x < 64; x += 1) {
      const sourceOffset = (y * 64 + x) * 4;
      for (let dy = 0; dy < 4; dy += 1) {
        for (let dx = 0; dx < 4; dx += 1) {
          const enlargedOffset = (((y * 4 + dy) * 256) + x * 4 + dx) * 4;
          for (let channel = 0; channel < 4; channel += 1) {
            if (source[sourceOffset + channel] !== enlarged[enlargedOffset + channel]) {
              fail(`4x PNG is not nearest-neighbor identical: ${id}`);
            }
          }
        }
      }
    }
  }
}

async function copy(source, destination) {
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.copyFile(source, destination);
}

function renderWebRegistry(items) {
  const entries = items.map(({ id, tier }) => `  ${JSON.stringify(id)}: {
    key: ${JSON.stringify(id)},
    tier: ${tier},
    imageUrl: ${JSON.stringify(`/creatures/slimes/official/shared/floors/${id}.png`)},
    imageScale: 1,
    surfaceY: 44,
    slimeFootY: 56,
  },`).join("\n");
  return `// Generated by scripts/import-static-slime-floors.mjs. Do not edit by hand.\n\nexport const SLIME_WEB_STATIC_FLOORS = {\n${entries}\n} as const;\n`;
}

function renderMobileRegistry(items) {
  const entries = items.map(({ id, tier }) => `  ${JSON.stringify(id)}: {
    key: ${JSON.stringify(id)},
    tier: ${tier},
    image: require(${JSON.stringify(`../assets/slimes/shared/floors/${id}.png`)}),
    imageScale: 4,
    surfaceY: 44,
    slimeFootY: 56,
  },`).join("\n");
  return `// Generated by scripts/import-static-slime-floors.mjs. Do not edit by hand.\n\nexport const SLIME_MOBILE_STATIC_FLOORS = {\n${entries}\n} as const;\n`;
}

async function main() {
  if (!process.argv[2]) fail("Usage: node scripts/import-static-slime-floors.mjs <SlimeAssets/floors>");
  const catalog = JSON.parse(await fs.readFile(catalogPath, "utf8"));
  if (catalog.type !== "static-floor-tier-catalog" || catalog.status !== "production") fail("Catalog is not production");
  if (catalog.canvas?.width !== 64 || catalog.canvas?.height !== 64 || catalog.surfaceY !== 44) fail("Catalog geometry changed");
  if (catalog.renderOrder !== "in-front-of-slime" || !Array.isArray(catalog.items) || catalog.items.length !== 10) fail("Catalog contract changed");

  const seen = new Set();
  const verified = [];
  for (const item of catalog.items) {
    const expectedTier = expectedTiers.get(item.id);
    if (!expectedTier || expectedTier !== item.tier || seen.has(item.id)) fail(`Unexpected floor tier or id: ${item.id}`);
    seen.add(item.id);
    if (item.folder !== item.id || Object.keys(item.files ?? {}).length !== 4) fail(`Unexpected file declaration: ${item.id}`);
    const folder = path.join(sourceRoot, item.folder);
    for (const [fileName, expectedHash] of Object.entries(item.files)) {
      if (await sha256(path.join(folder, fileName)) !== expectedHash) fail(`Hash mismatch: ${item.id}/${fileName}`);
    }

    const metadata = JSON.parse(await fs.readFile(path.join(folder, `${item.id}.json`), "utf8"));
    if (metadata.id !== item.id || metadata.type !== "static-floor" || metadata.tier !== item.tier
      || metadata.canvas?.width !== 64 || metadata.canvas?.height !== 64 || metadata.surfaceY !== 44
      || metadata.renderOrder !== "in-front-of-slime" || metadata.animation !== null
      || metadata.image !== `${item.id}.png`) fail(`Metadata contract mismatch: ${item.id}`);

    const sourcePng = path.join(folder, `${item.id}.png`);
    const source4x = path.join(folder, `${item.id}-4x.png`);
    const pixels = await readPixels(sourcePng, 64, 64);
    const pixels4x = await readPixels(source4x, 256, 256);
    verifyBinaryAlpha(pixels, item.id);
    verifyBinaryAlpha(pixels4x, item.id);
    verifyNearestNeighbor(pixels, pixels4x, item.id);
    await copy(sourcePng, path.join(webAssetRoot, `${item.id}.png`));
    await copy(source4x, path.join(mobileAssetRoot, `${item.id}.png`));
    verified.push({ id: item.id, tier: item.tier });
  }
  if (seen.size !== expectedTiers.size) fail("Catalog is missing an expected floor");

  await fs.writeFile(webRegistryPath, renderWebRegistry(verified), "utf8");
  await fs.writeFile(mobileRegistryPath, renderMobileRegistry(verified), "utf8");
  console.log(JSON.stringify({ importedStaticFloors: verified.length, tiers: { 1: 4, 2: 3, 3: 3 }, verifiedHashes: 40 }, null, 2));
}

await main();
